// jsdom has no matchMedia, which Amsterdam Design System components (e.g. the
// responsive Menu and PageHeader) use. In tests every media query "doesn't match".
if (!window.matchMedia) {
  window.matchMedia = (query: string) =>
    ({
      matches: false,
      media: query,
      onchange: null,
      addEventListener: () => {},
      removeEventListener: () => {},
      addListener: () => {},
      removeListener: () => {},
      dispatchEvent: () => false,
    }) as MediaQueryList
}
